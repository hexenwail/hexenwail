#ifndef RG_DEVICE_H
#define RG_DEVICE_H

#ifndef USE_SDL_GPU
#error rg_device.h belongs to the SDL_GPU backend; include it only under USE_SDL_GPU
#endif

#include "sdl_inc.h"
#include "gl_progid.h"		/* rprog_id_t */

/* True once the SDL_GPU device owns the window.  Read through R_GPU() at the
 * seams, so a later phase can turn it into something cheaper to test. */
extern qboolean	rg_active;
#define R_GPU()		(rg_active)

void	RG_Init (void);			/* cvars + commands, early in VID_Init */
qboolean RG_Requested (void);		/* -gpu on the command line */
/* Claim `window` for a new SDL_GPU device.  false leaves no device and the
 * window untouched, and the caller falls back to GL. */
qboolean RG_CreateDevice (SDL_Window *window, int vsync);
void	RG_Shutdown (void);
void	RG_SetVSync (int vsync);		/* vid_vsync: 0 off, 1 on, -1 adaptive */
/* Replaces SDL_GL_SwapWindow: submit the frame, and with `show` blit it to
 * the swapchain.  Called every frame, shown or not. */
void	RG_EndFrame (qboolean show);
void	RG_Status (void);		/* renderer_status lines */
const char *RG_DriverName (void);
/* gl_max_size under -gpu: the largest 2D texture dimension the device's
 * backend guarantees.  GL_Init_NullGL's only source for it; the null GL
 * table's GL_MAX_TEXTURE_SIZE is a placeholder (#513). */
int	RG_MaxTextureSize (void);

/* rg_null.c, generated by tools/gen_rg_null.py */
void	RG_NullGL_Install (void);
int	RG_NullGL_Verify (void);		/* entries no longer stubbed */
void	RG_NullGL_Report_f (void);
unsigned long RG_NullGL_Total (int *entry_points);

/* A seam whose SDL_GPU arm exists but cannot do this request yet (a texture
 * format, a sampler mode, a compute bind).  Counted by name and listed by
 * `gpu_unrouted` after the null table, so a routed call that the backend
 * drops is as visible as one that never reached it (#340 P1c). */
void	RG_NoteUnhandled (const char *what);
unsigned long RG_UnhandledTotal (int *kinds);
void	RG_UnhandledReport (void);
void	RG_UnhandledReset (void);

/* ------------------------------------------------------------------ */
/* The seams' SDL_GPU arms (#340 P1c).  Handles and enums stay GL-shaped:  */
/* the backend maps each GL name the engine already uses to its own        */
/* object (decision 1).                                                     */
/* ------------------------------------------------------------------ */

/* gl_texcreate.c (rg_resource.c).  `target` is the GL image target, as at
 * the seam: a cube face for one face of a cube map. */
void	RG_GenTextures (GLsizei n, GLuint *textures);
void	RG_DeleteTextures (GLsizei n, const GLuint *textures);
void	RG_TexImage (GLenum target, GLuint tex, GLint level, GLint internalformat,
		     GLsizei width, GLsizei height, GLsizei depth, GLenum format,
		     GLenum type, const void *pixels);
void	RG_TexStorage2D (GLenum target, GLuint tex, GLsizei levels, GLenum internalformat,
			 GLsizei width, GLsizei height);
void	RG_TexSubImage (GLenum target, GLuint tex, GLint level, GLint x, GLint y,
			GLsizei width, GLsizei height, GLint row_length,
			GLenum format, GLenum type, const void *pixels);
void	RG_TexParameter (GLenum target, GLuint tex, GLenum pname, GLint ivalue, GLfloat fvalue);

/* gl_texbind.c: what each texture unit holds, per target, exactly -- the
 * GL arm's shadow folds repeats and forgets on reset, this does neither. */
void	RG_BindTexture (GLuint unit, GLenum target, GLuint tex);

/* gl_shader.c R_Program_Create (rg_shader.c).  0 after logging why. */
GLuint	RG_ProgramCreate (rprog_id_t id);
/* The SDL_GPU uniform slot `block` is bound to in `program` (either stage),
 * or -1 if no stage declares it.  The GL arm's block index stand-in. */
GLint	RG_ProgramBlock (GLuint program, const char *block);
/* gl_shader.c R_ProgramSamplerLoc / R_ProgramSamplerUnit: the binding of
 * sampler `name` in either stage of `program`, -1 if neither declares it;
 * and the GL texture unit it reads, set in every stage that declares it.
 * A sampler nothing names a unit for reads none: each draw binds it a
 * placeholder and counts that (#340 P2a). */
GLint	RG_ProgramSampler (GLuint program, const char *name);
void	RG_ProgramSamplerUnit (GLuint program, const char *name, GLint unit);

/* gl_uniforms.c.  A CPU mirror and the GL binding point it stands for; the
 * backend pushes whatever was last flushed into the slot each program's
 * SPIR-V gives that block name. */
void	RG_UniformBlockRegister (const char *name, const void *mirror, int size);
void	RG_UniformBlockFlushed (const char *name);

/* gl_pipeline.c: dynamic state the pipeline object does not carry. */
void	RG_SetViewport (int x, int y, int width, int height);
void	RG_SetScissor (qboolean enable, int x, int y, int width, int height);
/* gl_pipeline.c R_ClearBuffers: glClear's GL_COLOR / DEPTH / STENCIL bits,
 * with the values it clears to.  Ends the open segment if it has draws, so
 * the clear is the next render pass's load op (#340 P2b). */
void	RG_Clear (GLbitfield mask, const float color[4], float depth, int stencil);

/* gl_vbo.c GL_ImmEnd / GL_ImmDraw (rg_frame.c): one immediate-mode batch in
 * the immvert_t layout, drawn with the bound program and the current draw
 * state.  `mode` is the GL primitive, quads and polygons included. */
void	RG_DrawImm (GLenum mode, const void *verts, int count, int stride);

/* gl_buffer.c's buffer and vertex-array seams (rg_buffer.c, #340 P2d), with
 * GL's signatures and GL's binding rules: GL_ARRAY_BUFFER is context state
 * that a pointer captures, GL_ELEMENT_ARRAY_BUFFER belongs to the bound VAO,
 * glVertexAttrib4f's values are context state.  `integer` is
 * glVertexAttribIPointer's flavour of the pointer call. */
void	RG_GenBuffers (GLsizei n, GLuint *buffers);
void	RG_DeleteBuffers (GLsizei n, const GLuint *buffers);
void	RG_BindBuffer (GLenum target, GLuint buffer);
void	RG_BufferData (GLenum target, GLsizeiptr size, const void *data, GLenum usage);
void	RG_BufferSubData (GLenum target, GLintptr offset, GLsizeiptr size, const void *data);
void	RG_GenVertexArrays (GLsizei n, GLuint *arrays);
void	RG_DeleteVertexArrays (GLsizei n, const GLuint *arrays);
void	RG_BindVertexArray (GLuint array);
void	RG_EnableVertexAttribArray (GLuint index, qboolean enable);
void	RG_VertexAttribPointer (GLuint index, GLint size, GLenum type, GLboolean normalized,
				qboolean integer, GLsizei stride, const void *pointer);
void	RG_VertexAttrib4f (GLuint index, GLfloat x, GLfloat y, GLfloat z, GLfloat w);

/* gl_buffer.c's indexed-binding and streaming seams (rg_buffer.c, #340 P2e).
 * A GL_SHADER_STORAGE_BUFFER binding point is what a draw binds to the
 * storage slot its program's reflection maps that point to; uniform-buffer
 * points reach nothing, since gl_uniforms.c's mirrors are pushed instead.
 * As in GL, both binds also set the target's generic binding.  RG_Upload is
 * GL_Upload: storage data streamed for this frame, handed back as a buffer
 * of its own at offset 0, because SDL_GPU binds a storage buffer whole. */
void	RG_BindBufferBase (GLenum target, GLuint index, GLuint buffer);
void	RG_BindBufferRange (GLenum target, GLuint index, GLuint buffer, GLintptr offset,
			    GLsizeiptr size);
void	RG_Upload (GLenum target, const void *data, size_t numbytes, GLuint *outbuf,
		   GLintptr *outofs);

/* gl_vbo.c R_DrawElements / R_DrawElementsInstanced (rg_frame.c): an
 * indexed draw from the bound VAO, with the bound program and the current
 * draw state.  `indices` is the byte offset into the element buffer, as in
 * GL; `type` the index width. */
void	RG_DrawIndexed (GLenum mode, GLsizei count, GLenum type, const void *indices,
			GLsizei instances);
/* gl_vbo.c R_DrawArrays (rg_frame.c, #340 P4e): `count` vertices from
 * `first`, with no vertex input.  The bound VAO must enable no attribute: the
 * only callers are fullscreen passes that build their vertices from
 * gl_VertexIndex, and a VAO with arrays is counted and dropped.  `first`
 * reaches the shader as GL's gl_VertexID does on Vulkan (gl_VertexIndex
 * includes it); D3D12's SV_VertexID does not (P7), and every caller passes 0. */
void	RG_DrawArrays (GLenum mode, GLint first, GLsizei count);

/* gl_fbo.c's framebuffer and renderbuffer seams (rg_target.c, #340 P4a-2),
 * with GL's signatures and binding rules; see gl_fbo.h. */
void	RG_GenFramebuffers (GLsizei n, GLuint *fbos);
void	RG_DeleteFramebuffers (GLsizei n, const GLuint *fbos);
void	RG_BindFramebuffer (GLenum target, GLuint fbo);
void	RG_FramebufferTexture2D (GLenum target, GLenum attachment, GLenum textarget,
				 GLuint texture, GLint level);
void	RG_FramebufferRenderbuffer (GLenum target, GLenum attachment, GLenum rbtarget,
				    GLuint renderbuffer);
GLenum	RG_CheckFramebufferStatus (GLenum target);
void	RG_DrawBuffers (GLsizei n, const GLenum *bufs);
void	RG_GenRenderbuffers (GLsizei n, GLuint *rbs);
void	RG_DeleteRenderbuffers (GLsizei n, const GLuint *rbs);
void	RG_BindRenderbuffer (GLenum target, GLuint rb);
void	RG_RenderbufferStorage (GLenum target, GLenum internalformat,
				GLsizei width, GLsizei height);
qboolean RG_BlitFramebuffer (GLint sx0, GLint sy0, GLint sx1, GLint sy1,
			     GLint dx0, GLint dy0, GLint dx1, GLint dy1,
			     GLbitfield mask, GLenum filter);
GLuint	RG_FramebufferBinding (GLenum pname);

/* gl_vidsdl.c GL_BeginRendering: the frame's render target size. */
void	RG_BeginFrame (int width, int height);

/* gl_vidsdl.c GL_Init_NullGL: the scene's depth target has a stencil
 * aspect, so have_stencil is true and the sky pre-pass and the stencilled
 * skybox run as on GL (#340 P2c).  The GL arm reads the visual's bits. */
qboolean RG_DepthHasStencil (void);

/* gl_postprocess.c GL_SoftDepth_Capture: the scene's depth format can be
 * sampled, so a copy of it can be read (#340 P4b).  Where it cannot, the
 * copy would be bound as a placeholder whose depth is the near plane. */
qboolean RG_DepthSampled (void);

#endif /* RG_DEVICE_H */
