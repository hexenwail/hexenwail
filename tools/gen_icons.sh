#!/usr/bin/env bash
# gen_icons.sh -- regenerate every Hexenwail application icon from one SVG.
#
# Source: engine/resource/hexenwail.svg, the Hammer of Thyrion "XII" icon as
# vectorised for the uHexen2 Flathub package (flathub/net.sourceforge.uhexen2.
# uhexen2, commit 09ab7c42, "Add scalable and 256x256 icon.").  It is kept
# byte-for-byte as published there; edit the art upstream or here, then rerun
# this script and commit everything it writes.
#
# Writes:
#   engine/resource/hexenwail.ico      Windows exe icon (win32res.rc), 16..256
#   engine/resource/hexenwail-256.png  Flatpak hicolor/256x256 + AppImage icon
#   engine/resource/hexenwail_icon.h   128px PNG bytes, SDL window icon at runtime
#   web/icons/icon.svg                 PWA scalable icon (copy of the source)
#   web/icons/icon-192.png, icon-512.png   PWA manifest icons (transparent)
#   web/icons/icon-180.png             apple-touch-icon (iOS fills alpha with
#                                      black, so it is flattened on the page bg)
#
# Checked by tools/test_icons.py (sizes, formats, and that every build points
# at these files).  Rendering is librsvg; a different librsvg version may
# change bytes, which is fine -- the test checks shape, not hashes.
set -euo pipefail

SELF=$(realpath "$0")
cd "$(dirname "$SELF")/.."
SVG=engine/resource/hexenwail.svg
[ -f "$SVG" ] || { echo "missing $SVG" >&2; exit 1; }

if ! command -v rsvg-convert >/dev/null || ! command -v magick >/dev/null \
   || ! command -v xxd >/dev/null || ! command -v python3 >/dev/null; then
	exec nix shell nixpkgs#librsvg nixpkgs#imagemagick nixpkgs#xxd nixpkgs#python3 \
		-c bash "$SELF" "$@"
fi

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

render() {	# render <size> <out.png>
	rsvg-convert -w "$1" -h "$1" "$SVG" -o "$tmp/raw.png"
	# -strip drops the timestamp chunks so reruns are byte-stable.
	magick "$tmp/raw.png" -strip -define png:exclude-chunks=date,time "$2"
}

for s in 16 24 32 48 64 128 256 512; do
	render "$s" "$tmp/$s.png"
done

# Windows: the 256 entry is stored PNG-compressed (Vista+ convention), the rest
# as BMP so XP-era shells and windres-era tooling read them too.
# ImageMagick writes every entry as BMP (a 256 BMP alone is 270 KB), so each
# small size goes through magick on its own and the ICO is assembled here.
for s in 16 24 32 48 64 128; do
	magick "$tmp/$s.png" -type TrueColorAlpha "$tmp/$s.ico"
done
python3 -I - "$tmp" engine/resource/hexenwail.ico <<'PY'
import struct, sys
tmp, out = sys.argv[1], sys.argv[2]
entries = []
for s in (16, 24, 32, 48, 64, 128):
    d = open(f"{tmp}/{s}.ico", "rb").read()
    assert struct.unpack("<HHH", d[:6]) == (0, 1, 1), s
    w, h, colors, _, planes, bpp, size, off = struct.unpack("<BBBBHHII", d[6:22])
    assert (w, h, bpp) == (s, s, 32), (s, w, h, bpp)
    entries.append((s, planes, bpp, d[off:off + size]))
entries.append((256, 1, 32, open(f"{tmp}/256.png", "rb").read()))
hdr = struct.pack("<HHH", 0, 1, len(entries))
off = 6 + 16 * len(entries)
dirs, blobs = b"", b""
for s, planes, bpp, blob in entries:
    dirs += struct.pack("<BBBBHHII", s % 256, s % 256, 0, 0, planes, bpp,
                        len(blob), off + len(blobs))
    blobs += blob
open(out, "wb").write(hdr + dirs + blobs)
PY

cp "$tmp/256.png" engine/resource/hexenwail-256.png

{
	echo "/* hexenwail_icon.h -- GENERATED by tools/gen_icons.sh, do not edit."
	echo " * 128x128 RGBA PNG of engine/resource/hexenwail.svg, decoded with"
	echo " * stb_image by VID_SetIcon (gl_vidsdl.c) for the SDL window icon. */"
	echo "#define HEXENWAIL_ICON_SIZE 128"
	echo "static const unsigned char hexenwail_icon_png[] = {"
	xxd -i < "$tmp/128.png"
	echo "};"
} > engine/resource/hexenwail_icon.h

cp "$SVG" web/icons/icon.svg
render 192 web/icons/icon-192.png
cp "$tmp/512.png" web/icons/icon-512.png
rsvg-convert -w 180 -h 180 "$SVG" -o "$tmp/180.png"
magick "$tmp/180.png" -background '#12101b' -flatten -strip \
	-define png:exclude-chunks=date,time web/icons/icon-180.png

echo "icons regenerated from $SVG"
