#!/usr/bin/env python3
"""Generate engine/h2shared/gl_progid_refl.h, the per-stage resource counts
SDL_GPU needs to create each offline shader blob (GitHub #340, phase P1b).

SDL_CreateGPUShader takes num_samplers, num_storage_textures,
num_storage_buffers and num_uniform_buffers; SDL_CreateGPUComputePipeline
takes num_samplers, num_readonly_storage_textures/_buffers,
num_readwrite_storage_textures/_buffers, num_uniform_buffers and the
threadcount.  None of that can be asked of the blob at run time, so it is
read here, once, from the Vulkan SPIR-V shaders_spirv compiles -- the same
bytes SDL_GPU will be handed -- with tools/test_sdlgpu_bindings.py's
decoder, and written into a header gl_shader.c includes.

The header is checked in rather than generated by the engine build: GLES
and the web builds compile gl_shader.c too, and #340 decision 6 makes
glslangValidator a build input only where USE_SDL_GPU is on.  So the gate is
the other way round -- shaders-spirv.yml regenerates it with --check and fails
when the checked-in copy differs, tools/test_program_routing.py (lint.yml)
fails when its rows are not exactly the offline copies EmbedShaders writes,
and a USE_SDL_GPU build's EmbedSpirv.cmake fails when they are not the
blobs it embeds.

One row per <blob>.vk.spv, sorted by name.  A graphics stage's storage is
read-only (test_sdlgpu_bindings.py fails a writable one), so its rw_ counts
are 0; its threadcount is 0.

Usage:  gen_program_reflection.py SPIRV_DIR [--out FILE] [--check] [--cross CROSS_DIR]

SPIRV_DIR is <build>/engine/generated/spirv.  Without --out, writes the
checked-in header.  --check writes nothing and fails if the header would
change.  --cross names CrossCompileShaders.cmake's output
(<build>/engine/generated/cross) and also fails any row that disagrees with
shadercross's reflection JSON of the same blob -- a second decoder, written
against SDL_GPU itself, so a bug in this one cannot pass on its own say-so.
Stock python3 only.
"""
from pathlib import Path
import argparse
import json
import struct
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import test_sdlgpu_bindings as sb  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
HEADER = ROOT / "engine/h2shared/gl_progid_refl.h"

OP_EXECUTION_MODE = 16
OP_EXECUTION_MODE_ID = 331
MODE_LOCAL_SIZE = 17
MODE_LOCAL_SIZE_ID = 38

STAGE_ENUM = {"vertex": "RPROG_REFL_VERTEX", "fragment": "RPROG_REFL_FRAGMENT",
              "compute": "RPROG_REFL_COMPUTE"}
COUNT_CLASSES = (sb.SAMPLED, sb.RO_STORAGE_TEX, sb.RO_STORAGE_BUF,
                 sb.RW_STORAGE_TEX, sb.RW_STORAGE_BUF, sb.UBO)


def local_size(data):
    """The compute stage's LocalSize execution mode, or raise."""
    endian = "<" if struct.unpack_from("<I", data)[0] == sb.MAGIC else ">"
    words = struct.unpack(endian + "%dI" % (len(data) // 4), data)
    i = 5
    while i < len(words):
        wc, op = words[i] >> 16, words[i] & 0xFFFF
        if wc == 0:
            break
        ops = words[i + 1:i + wc]
        if op == OP_EXECUTION_MODE and len(ops) >= 5 and ops[1] == MODE_LOCAL_SIZE:
            return tuple(ops[2:5])
        if op == OP_EXECUTION_MODE_ID and len(ops) >= 2 and ops[1] == MODE_LOCAL_SIZE_ID:
            raise sb.SpirvError("LocalSizeId (a specialization-constant workgroup size); "
                                "SDL_GPU takes the threadcount as numbers")
        i += wc
    raise sb.SpirvError("compute stage with no LocalSize execution mode")


def rows(spirv_dir):
    out, errors = [], []
    files = sorted(spirv_dir.glob("*.vk.spv"))
    if not files:
        errors.append("%s: no *.vk.spv -- build the shaders_spirv target first" % spirv_dir)
    for f in files:
        blob = f.name[:-len(".vk.spv")]
        data = f.read_bytes()
        try:
            stage, resources, problems = sb.parse(data)
            threads = local_size(data) if stage == "compute" else (0, 0, 0)
        except sb.SpirvError as e:
            errors.append("%s: %s" % (blob, e))
            continue
        problems += sb.check(stage, resources)
        if problems:
            errors += ["%s: %s" % (blob, p) for p in problems]
            continue
        counts = [sum(1 for r in resources if r.cls == c) for c in COUNT_CLASSES]
        if any(n > 255 for n in counts) or any(t > 65535 for t in threads):
            errors.append("%s: a count does not fit the row's field" % blob)
            continue
        out.append((blob, stage, counts, threads))
    return out, errors


def render(table):
    lines = [
        "/* gl_progid_refl.h -- per-stage SDL_GPU resource counts, one row per offline blob",
        " *",
        " * GENERATED by tools/gen_program_reflection.py from the Vulkan SPIR-V the",
        " * shaders_spirv target compiles, <build>/engine/generated/spirv/<blob>.vk.spv.",
        " * Do not edit: regenerate with",
        " *",
        " *   cmake --build <build> --target shaders_spirv",
        " *   python3 tools/gen_program_reflection.py <build>/engine/generated/spirv",
        " *",
        " * shaders-spirv.yml fails when this is stale, test_program_routing.py when",
        " * its rows are not exactly EmbedShaders.cmake's offline copies.  Included by",
        " * gl_shader.c only.  GitHub #340 (P1b).",
        " */",
        "",
        "static const rprog_refl_t rprog_refl[] = {",
        "\t/* blob, stage, samplers, ro storage textures, ro storage buffers,",
        "\t * rw storage textures, rw storage buffers, uniform buffers, threadcount */",
    ]
    for blob, stage, counts, threads in table:
        lines.append('\t{ "%s", %s, %s, { %d, %d, %d } },'
                     % (blob, STAGE_ENUM[stage], ", ".join(str(n) for n in counts), *threads))
    lines += ["};", ""]
    return "\n".join(lines)


def cross_check(table, cross_dir):
    """Every row against shadercross's own reflection of the same blob
    (CrossCompileShaders.cmake's <blob>.json), a second decoder written
    against SDL_GPU itself."""
    errors = []
    for blob, stage, counts, threads in table:
        p = cross_dir / (blob + ".json")
        if not p.exists():
            errors.append("%s: no %s from shaders_cross" % (blob, p))
            continue
        j = json.loads(p.read_text())
        samp, rotex, robuf, rwtex, rwbuf, ubo = counts
        if stage == "compute":
            want = {"samplers": samp, "readonly_storage_textures": rotex,
                    "readonly_storage_buffers": robuf, "readwrite_storage_textures": rwtex,
                    "readwrite_storage_buffers": rwbuf, "uniform_buffers": ubo,
                    "threadcount_x": threads[0], "threadcount_y": threads[1], "threadcount_z": threads[2]}
        else:
            want = {"samplers": samp, "storage_textures": rotex, "storage_buffers": robuf,
                    "uniform_buffers": ubo}
        for k, v in want.items():
            if j.get(k) != v:
                errors.append("%s: %s is %d here, %r in shadercross's %s" % (blob, k, v, j.get(k), p.name))
    return errors


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    ap.add_argument("spirv_dir", type=Path)
    ap.add_argument("--out", type=Path, default=HEADER)
    ap.add_argument("--check", action="store_true",
                    help="fail if the header would change; write nothing")
    ap.add_argument("--cross", type=Path,
                    help="shaders_cross output (<build>/engine/generated/cross): also check every row "
                         "against shadercross's reflection JSON of the same blob")
    args = ap.parse_args(argv)

    table, errors = rows(args.spirv_dir)
    if not errors and args.cross is not None:
        errors = cross_check(table, args.cross)
    if errors:
        for e in errors:
            print("FAIL: " + e, file=sys.stderr)
        return 1
    text = render(table)
    if args.check:
        have = args.out.read_text() if args.out.exists() else ""
        if have != text:
            print("FAIL: %s is stale against %s; regenerate it with tools/gen_program_reflection.py"
                  % (args.out, args.spirv_dir), file=sys.stderr)
            old = {l.strip() for l in have.split("\n") if l.strip().startswith('{ "')}
            new = {l.strip() for l in text.split("\n") if l.strip().startswith('{ "')}
            for l in sorted(old - new):
                print("  - " + l, file=sys.stderr)
            for l in sorted(new - old):
                print("  + " + l, file=sys.stderr)
            return 1
        print("PASS program reflection: %s matches %d Vulkan SPIR-V stages%s (#340 P1b)"
              % (args.out.name, len(table),
                 ", and shadercross's reflection of each" if args.cross is not None else ""))
        return 0
    args.out.write_text(text)
    print("wrote %s: %d rows" % (args.out, len(table)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
