#!/usr/bin/env python3
"""Every GPU program is built by id, through R_Program_Create, from a row of
gl_shader.c's program table (GitHub #340, phase P1b).

GL builds a program from GLSL at run time.  SDL_GPU cannot compile GLSL: it
creates each stage from an offline blob and has to be told the stage's
resource counts.  So the SDL_GPU backend needs every program the renderer
can ask for to be a name it can look up, with a blob and a reflection row
per stage -- and it needs no other way for a program to come into being.
gl_progid.h's rprog_id_t is that name and gl_shader.c's rprog_defs[] the
table; this lint holds the shape:

  * No raw program-building GL call outside gl_shader.c: glCreateShader,
    glShaderSource, glCompileShader, glCreateProgram, glAttachShader,
    glDetachShader, glLinkProgram, glBindAttribLocation,
    glBindFragDataLocation(Indexed), glCreateShaderProgramv,
    glProgramBinary, glShaderBinary, glSpecializeShader, glProgramParameteri
    and the ARB shader-object spellings -- raw, _fp, extension-suffixed,
    through a pointer or a #define, or taken as a value (the same patterns
    as tools/test_texture_create_routing.py).  Inside gl_shader.c, the stage
    calls only in RP_CompileStage and the program calls only in
    R_Program_Create.  Exempt: the loader table gl_func.h, the null-GL table
    rg_null.c, and web_canvas_gl2.c -- WEBSOFT's raw-GLES presenter, a
    separate renderer that never runs SDL_GPU.
  * The only compile is a row: RP_CompileStage hands glShaderSource exactly
    its stage's header and body, R_Program_Create gets the stage from
    RP_Def (rprog_defs[id]) and only it calls RP_CompileStage.
  * Every R_Program_Create argument is an id: an RPROG_* enumerator, an
    element of a `static const rprog_id_t x[] = { RPROG_* ... }` array in
    the same file, or an rprog_id_t parameter of the calling function whose
    own callers pass one of those.  R_Program_Create named any other way (a
    function pointer, a macro) fails.
  * No program-family entry point looked up by name (GetProcAddress with
    its string) outside the loader gl_vidsdl.c.
  * Each graphics row links as its builder did before ids: RPROG_LINK_PLAIN
    for programs requested from gl_postprocess.c, RPROG_LINK_TEXCOORD for
    the instanced alias pair, RPROG_LINK_ATTRIBS (all four ATTR_* bindings,
    each still in R_Program_Create) for the rest.
  * The index -> id maps whose order is the variant -- gl_ssao.c's eval_id
    (QUALITY = index + 1), gl_postprocess.c's pp_palette_init_id (MODE =
    softemu_metric_t) -- are pinned element by element.
  * The table and the enum agree: one row per enumerator (RPROG_COUNT
    aside), no row for anything else, each row's name the enumerator in
    lower case without RPROG_, its link mode an RPROG_LINK_*, two stages
    (a _vert body then a _frag) or, for RPROG_LINK_COMPUTE, one _comp.
  * Every stage's blob is the offline copy EmbedShaders.cmake writes for
    that body and that header's #define set (the plain stage, its OIT twin
    or a variants.txt variant, computed as tools/test_shader_variants.py
    does) -- so an id cannot name a blob that does not exist or is another
    program's.
  * Reflection: gl_progid_refl.h (generated by
    tools/gen_program_reflection.py, checked against the SPIR-V in
    shaders-spirv.yml) has exactly one row per offline copy, its stage kind
    matching the copy's, and is included by gl_shader.c only.
  * No stale id: every enumerator reaches some R_Program_Create call.

The table is read desktop-side (USE_GLES undefined), as test_shader_variants
reads it; the ES tier's rows are a subset, compiled by
scripts/webgl-engine-shader-smoke.mjs.

Usage:  test_program_routing.py [--root DIR]
Stock python3 only.
"""
from pathlib import Path
import argparse
import re
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import test_shader_variants as tsv  # noqa: E402
import test_texture_create_routing as ttr  # noqa: E402

MODULE = "engine/h2shared/gl_shader.c"
ENUM_FILE = "engine/h2shared/gl_progid.h"
REFL_FILE = "engine/h2shared/gl_progid_refl.h"
EXEMPT = {
    "engine/h2shared/gl_func.h",		# the loader table: declares every _fp
    "engine/h2shared/rg_null.c",		# the generated null-GL table
    "engine/h2shared/web_canvas_gl2.c",	# WEBSOFT's raw-GLES presenter
}
SUFFIXES = (".c", ".h", ".inc")

# GL program-family entry points -> the gl_shader.c function allowed to call it.
STAGE_CALLS = ("CreateShader", "ShaderSource", "CompileShader")
PROGRAM_CALLS = ("CreateProgram", "AttachShader", "BindAttribLocation", "LinkProgram")
FORBIDDEN = ("DetachShader", "BindFragDataLocation", "BindFragDataLocationIndexed",
             "CreateShaderProgramv", "ProgramBinary", "ShaderBinary", "SpecializeShader",
             "ProgramParameteri", "CreateShaderObject", "CreateProgramObject",
             "AttachObject", "ShaderSourceARB", "CreateShaderProgramEXT")
ALLOWED_IN = {n: "RP_CompileStage" for n in STAGE_CALLS}
ALLOWED_IN.update({n: "R_Program_Create" for n in PROGRAM_CALLS})

NAMES = "|".join(sorted(STAGE_CALLS + PROGRAM_CALLS + FORBIDDEN, key=len, reverse=True))
NAME = r"\b(gl(" + NAMES + r")(?:ARB|EXT|OES|KHR|NV|AMD)?(?:_fp)?)\b"
CALL_RE = re.compile(NAME + r"\s*\)?\s*\(")
BARE_RE = re.compile(NAME + r"(?!\s*\)?\s*\()(?!\s*[!=]=)")
VALUE_RE = re.compile(r"(?:(?<![=!<>])=|(?<!&)&(?!&))\s*" + ttr._CAST + r"\(?\s*" + NAME
                      + r"(?!\s*\)?\s*\()(?!\s*[!=]=)")
# Not called, and not the target of an assignment either: the loader's
# "glCreateShader_fp = SDL_GL_GetProcAddress (...)" as a function's first
# statement follows a "{" without being an initializer entry.
_NOT_CALLED = ttr._NOT_CALLED + r"(?!\s*=(?!=))"
HANDOFF_RE = re.compile(r"(?:[,?:{]|\breturn\b)\s*" + ttr._CAST + NAME + _NOT_CALLED)
ARG_RE = re.compile(r"\b(?!(?:if|while|for|switch|return|sizeof)\b)[A-Za-z_]\w*\s*\(\s*"
                    + ttr._CAST + NAME + _NOT_CALLED)
FUNC_RE = re.compile(r"^[A-Za-z_][\w \t\*]*?\b([A-Za-z_]\w*)\s*\(([^;{}()]*)\)\s*\{", re.M)
KEYWORDS = {"if", "while", "for", "switch", "return", "sizeof", "do", "else"}
LINK_MODES = {"RPROG_LINK_ATTRIBS", "RPROG_LINK_TEXCOORD", "RPROG_LINK_PLAIN", "RPROG_LINK_COMPUTE"}
REFL_STAGE = {"vert": "RPROG_REFL_VERTEX", "frag": "RPROG_REFL_FRAGMENT", "comp": "RPROG_REFL_COMPUTE"}


def line_of(text, pos):
    return text.count("\n", 0, pos) + 1


def matching_brace(text, i):
    """Index of the '}' closing the '{' at i (text already blanked)."""
    depth = 0
    for j in range(i, len(text)):
        if text[j] == "{":
            depth += 1
        elif text[j] == "}":
            depth -= 1
            if depth == 0:
                return j
    return len(text)


def functions(text):
    """[(name, params text, body start, body end)] of the function definitions."""
    out = []
    for m in FUNC_RE.finditer(text):
        if m.group(1) in KEYWORDS:
            continue
        start = m.end() - 1
        out.append((m.group(1), m.group(2), start, matching_brace(text, start)))
    return out


def enclosing(funcs, pos):
    for f in funcs:
        if f[2] <= pos <= f[3]:
            return f
    return None


def split_top(s):
    """Split a C argument list at its top-level commas."""
    out, cur, depth = [], "", 0
    for c in s:
        if c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
        if c == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += c
    if cur.strip():
        out.append(cur.strip())
    return out


def call_args(text, pos):
    """The argument list of the call whose '(' is at or after pos."""
    i = text.index("(", pos)
    depth = 0
    for j in range(i, len(text)):
        if text[j] == "(":
            depth += 1
        elif text[j] == ")":
            depth -= 1
            if depth == 0:
                return split_top(text[i + 1:j]), j
    return [], len(text)


def scan_raw(rel, text, funcs, errors):
    for m in CALL_RE.finditer(text):
        full, name = m.group(1), m.group(2)
        if rel == MODULE and name in ALLOWED_IN:
            f = enclosing(funcs, m.start())
            if f is not None and f[0] == ALLOWED_IN[name]:
                continue
            errors.append("%s:%d: %s outside %s -- every program is built by R_Program_Create "
                          "from its rprog_defs row" % (rel, line_of(text, m.start()), full,
                                                       ALLOWED_IN[name]))
            continue
        errors.append("%s:%d: %s -- program creation outside gl_shader.c; build it by id with "
                      "R_Program_Create (gl_progid.h)" % (rel, line_of(text, m.start()), full))
    for d in ttr.DEFINE_RE.finditer(text):
        for m in BARE_RE.finditer(d.group(0)):
            errors.append("%s:%d: #define aliases %s -- program creation outside R_Program_Create"
                          % (rel, line_of(text, d.start() + m.start()), m.group(1)))
    seen = set()
    for rx in (VALUE_RE, HANDOFF_RE, ARG_RE):
        for m in rx.finditer(text):
            if m.start(1) in seen:
                continue
            seen.add(m.start(1))
            errors.append("%s:%d: %s taken as a value -- program creation outside R_Program_Create"
                          % (rel, line_of(text, m.start(1)), m.group(1)))


def read_enum(text, errors):
    m = re.search(r"typedef\s+enum\s*\{(.*?)\}\s*rprog_id_t\s*;", text, re.S)
    if not m:
        errors.append("%s: no `typedef enum { ... } rprog_id_t;`" % ENUM_FILE)
        return []
    names = []
    for part in m.group(1).split(","):
        part = part.strip()
        if not part:
            continue
        if not re.match(r"^RPROG_[A-Z0-9_]+$", part):
            errors.append("%s: enumerator %r: ids are bare RPROG_* names, numbered by position"
                          % (ENUM_FILE, part))
            continue
        names.append(part)
    if not names or names[-1] != "RPROG_COUNT":
        errors.append("%s: rprog_id_t must end with RPROG_COUNT" % ENUM_FILE)
    return [n for n in names if n != "RPROG_COUNT"]


class Resolver:
    """Proves each R_Program_Create argument is an id, collecting which."""

    def __init__(self, texts, enum, errors):
        self.texts, self.enum, self.errors = texts, set(enum), errors
        self.funcs = {rel: functions(t) for rel, t in texts.items()}
        self.reached = {}           # id -> the files that request it
        self.sites = 0

    def id_arrays(self, rel):
        out = {}
        for m in re.finditer(r"\bstatic\s+const\s+rprog_id_t\s+(\w+)\s*\[[^\]]*\]\s*=\s*\{([^}]*)\}",
                             self.texts[rel]):
            vals = re.sub(r"\[\s*\w+\s*\]\s*=", "", m.group(2))
            items = [v.strip() for v in vals.split(",") if v.strip()]
            out[m.group(1)] = items
        return out

    def resolve(self, rel, expr, pos, where, depth=0):
        expr = expr.strip()
        while expr.startswith("(") and expr.endswith(")"):
            expr = expr[1:-1].strip()
        if expr in self.enum:
            self.reached.setdefault(expr, set()).add(rel)
            return
        f = enclosing(self.funcs[rel], pos)
        m = re.match(r"^(\w+)\s*\[.*\]$", expr, re.S)
        if m:
            # A const id array: file scope, or local to the calling function.
            scope = self.texts[rel] if f is None else self.texts[rel][f[2]:f[3]]
            arrays = self.id_arrays(rel)
            lm = re.search(r"\bstatic\s+const\s+rprog_id_t\s+%s\s*\[[^\]]*\]\s*=\s*\{([^}]*)\}"
                           % re.escape(m.group(1)), scope)
            items = arrays.get(m.group(1)) if lm is None else \
                [v.strip() for v in re.sub(r"\[\s*\w+\s*\]\s*=", "", lm.group(1)).split(",") if v.strip()]
            if items is not None:
                bad = [v for v in items if v not in self.enum]
                if bad:
                    self.errors.append("%s: %s holds %s, not an rprog_id_t enumerator"
                                       % (where, m.group(1), ", ".join(bad)))
                for v in items:
                    if v in self.enum:
                        self.reached.setdefault(v, set()).add(rel)
                return
        if re.match(r"^\w+$", expr) and f is not None and depth < 4:
            params = split_top(f[1])
            idx = next((k for k, p in enumerate(params)
                        if re.match(r"^(?:const\s+)?rprog_id_t\s+%s$" % re.escape(expr), p)), None)
            if idx is not None:
                callers = 0
                text = self.texts[rel]
                for cm in re.finditer(r"\b%s\s*\(" % re.escape(f[0]), text):
                    if enclosing(self.funcs[rel], cm.start()) is None:
                        continue    # its definition or a prototype: file scope
                    callers += 1
                    args, _close = call_args(text, cm.start())
                    cw = "%s:%d" % (rel, line_of(text, cm.start()))
                    if len(args) <= idx:
                        self.errors.append("%s: %s called with %d arguments" % (cw, f[0], len(args)))
                        continue
                    self.resolve(rel, args[idx], cm.start(), cw, depth + 1)
                if callers == 0:
                    self.errors.append("%s: %s's id parameter %s has no caller in %s to take it "
                                       "from (an extern helper is not followed)" % (where, f[0], expr, rel))
                return
        self.errors.append("%s: R_Program_Create (%s) -- not an RPROG_* id, a const rprog_id_t "
                           "array of them, or an rprog_id_t parameter whose callers pass one; a "
                           "program built from a run-time value is not a table row"
                           % (where, expr))

    def run(self):
        for rel, text in sorted(self.texts.items()):
            for m in re.finditer(r"\bR_Program_Create\b", text):
                where = "%s:%d" % (rel, line_of(text, m.start()))
                rest = text[m.end():]
                if not re.match(r"\s*\(", rest):
                    self.errors.append("%s: R_Program_Create named other than as a call (a pointer, a "
                                       "macro?); a program built through it would escape this lint"
                                       % where)
                    continue
                f = enclosing(self.funcs[rel], m.start())
                args, close = call_args(text, m.start())
                if f is None:
                    after = text[close + 1:].lstrip()
                    if rel == ENUM_FILE and after.startswith(";"):
                        continue    # the prototype
                    if rel == MODULE and after.startswith("{"):
                        continue    # the definition
                    self.errors.append("%s: R_Program_Create outside a function" % where)
                    continue
                if len(args) != 1:
                    self.errors.append("%s: R_Program_Create takes one id" % where)
                    continue
                self.sites += 1
                self.resolve(rel, args[0], m.start(), where)


def check_module_shape(text, funcs, errors):
    """The only compile is a row's two chunks."""
    byname = {f[0]: text[f[2]:f[3]] for f in funcs}
    leaf = byname.get("RP_CompileStage", "")
    for need, why in ((r"chunks\[0\]\s*=\s*st->header\s*;", "set chunk 0 to the row's header"),
                      (r"chunks\[1\]\s*=\s*st->body\s*;", "set chunk 1 to the row's body"),
                      (r"glShaderSource_fp\s*\(\s*shader\s*,\s*2\s*,\s*chunks\s*,\s*NULL\s*\)",
                       "hand glShaderSource exactly those two chunks")):
        if not re.search(need, leaf):
            errors.append("%s: RP_CompileStage must %s" % (MODULE, why))
    if len(re.findall(r"\bglShaderSource_fp\b", leaf)) != 1:
        errors.append("%s: RP_CompileStage must call glShaderSource_fp exactly once" % MODULE)
    create = byname.get("R_Program_Create", "")
    if not re.search(r"=\s*RP_Def\s*\(\s*id\s*\)", create):
        errors.append("%s: R_Program_Create must take its row from RP_Def (id)" % MODULE)
    if not re.search(r"RP_CompileStage\s*\(\s*def\s*,[^;]*&def->stage\[i\]\s*\)", create):
        errors.append("%s: R_Program_Create must compile &def->stage[i] of that row" % MODULE)
    rpdef = byname.get("RP_Def", "")
    if not re.search(r"&rprog_defs\[id\]", rpdef):
        errors.append("%s: RP_Def must return &rprog_defs[id]" % MODULE)
    for name in ("RP_CompileStage", "RP_Def"):
        uses = [m.start() for m in re.finditer(r"\b%s\s*\(" % name, text)]
        for u in uses:
            f = enclosing(funcs, u)
            if f is None:
                continue    # its definition
            if f[0] != "R_Program_Create" and not (name == "RP_Def" and f[0] in
                                                    ("R_Program_Name", "R_Program_Blob")):
                errors.append("%s:%d: %s called from %s; only R_Program_Create compiles a row"
                              % (MODULE, line_of(text, u), name, f[0]))


# How each program linked before ids (#340 P1b), which its row must keep:
# GL_LinkProgram bound all four ATTR_* names; the instanced alias pair bound
# a_texcoord only; gl_postprocess.c's PP_LinkProgram and OIT resolve bound
# none.  Pinned by who requests the id, so a new program inherits its file's
# rule and a row cannot drift on its own.
PLAIN_FILES = {"engine/h2shared/gl_postprocess.c"}
TEXCOORD_IDS = {"RPROG_ALIAS_INSTANCED", "RPROG_ALIAS_INSTANCED_NP"}
ATTRIB_BINDS = (("ATTR_POSITION", "a_position"), ("ATTR_TEXCOORD", "a_texcoord"),
                ("ATTR_LMCOORD", "a_lmcoord"), ("ATTR_COLOR", "a_color"))

# The index -> id maps whose order is the program's meaning: element i of
# eval_id is r_ssao i+1's QUALITY, pp_palette_init_id[metric] is MODE=metric.
# The old call sites formatted the define from the index, so these were right
# by construction; now a swapped element would compile the wrong variant.
PINNED_MAPS = {
    ("engine/h2shared/gl_ssao.c", "eval_id"):
        ["RPROG_SSAO_EVALUATE_Q1", "RPROG_SSAO_EVALUATE_Q2", "RPROG_SSAO_EVALUATE_Q3"],
    ("engine/h2shared/gl_postprocess.c", "pp_palette_init_id"):
        ["[SOFTEMU_METRIC_NAIVE] = RPROG_SOFTEMU_LUT_MODE0",
         "[SOFTEMU_METRIC_RIEMERSMA] = RPROG_SOFTEMU_LUT_MODE1",
         "[SOFTEMU_METRIC_OKLAB] = RPROG_SOFTEMU_LUT_MODE2"],
}


def check_link_modes(rows, reached, texts, errors):
    for row in rows:
        if row.link == "RPROG_LINK_COMPUTE" or row.id not in reached:
            continue
        files = reached[row.id]
        want = ("RPROG_LINK_TEXCOORD" if row.id in TEXCOORD_IDS else
                "RPROG_LINK_PLAIN" if files <= PLAIN_FILES else
                "RPROG_LINK_ATTRIBS" if not files & PLAIN_FILES else None)
        if want is None:
            errors.append("%s: %s is requested from %s; a post-process program and another one "
                          "cannot share a row" % (row.where, row.id, ", ".join(sorted(files))))
        elif row.link != want:
            errors.append("%s: %s links with %s; a program built from %s linked with %s before ids"
                          % (row.where, row.id, row.link, ", ".join(sorted(files)), want))
    module = texts.get(MODULE, "")
    create = next((module[f[2]:f[3]] for f in functions(module) if f[0] == "R_Program_Create"), "")
    for slot, name in ATTRIB_BINDS:
        if not re.search(r"glBindAttribLocation_fp\s*\(\s*prog\s*,\s*%s\s*," % slot, create):
            errors.append("%s: R_Program_Create no longer binds %s (%s) for RPROG_LINK_ATTRIBS"
                          % (MODULE, slot, name))
    for (rel, name), want in PINNED_MAPS.items():
        m = re.search(r"\bconst\s+rprog_id_t\s+%s\s*\[[^\]]*\]\s*=\s*\{([^}]*)\}" % name,
                      texts.get(rel, ""))
        have = [" ".join(v.split()) for v in m.group(1).split(",") if v.strip()] if m else None
        if have != want:
            errors.append("%s: %s must be { %s }: the index is the variant (got %s)"
                          % (rel, name, ", ".join(want), have))


# A GL entry point looked up by name hands the call to a pointer the scan
# above cannot see.  Only the loader may do that for the program family.
LOOKUP_RE = re.compile(r'GetProcAddress\w*\s*\(\s*"(gl(?:%s)\w*)"' % NAMES)
LOADERS = {"engine/h2shared/gl_vidsdl.c"}


def check_lookups(root, errors):
    for path in sorted(p for p in (root / "engine").rglob("*") if p.suffix in SUFFIXES):
        rel = path.relative_to(root).as_posix()
        if rel in LOADERS or rel in EXEMPT:
            continue
        text = path.read_text(errors="replace")
        for m in LOOKUP_RE.finditer(text):
            errors.append("%s:%d: looks %s up by name -- program creation outside R_Program_Create"
                          % (rel, line_of(text, m.start()), m.group(1)))


def check_table(an, enum, offline, consts, errors):
    rows = an.table(errors)
    by_id = {}
    names = {}
    blobs_used = set()
    for row in rows:
        w = row.where
        if row.id in by_id:
            errors.append("%s: %s has a second row (first at %s)" % (w, row.id, by_id[row.id].where))
            continue
        by_id[row.id] = row
        if row.id not in enum:
            errors.append("%s: row %s is no rprog_id_t enumerator" % (w, row.id))
            continue
        want = row.id[len("RPROG_"):].lower()
        if row.name != want:
            errors.append("%s: %s is named %r; a row's name is its id, %r" % (w, row.id, row.name, want))
        if row.name in names:
            errors.append("%s: name %r is also %s's" % (w, row.name, names[row.name]))
        names[row.name] = row.id
        if row.link not in LINK_MODES:
            errors.append("%s: %s links with %s, not an RPROG_LINK_* mode" % (w, row.id, row.link))
        compute = row.link == "RPROG_LINK_COMPUTE"
        want_ext = ["comp"] if compute else ["vert", "frag"]
        exts = [tsv.stage_file(str(b)).rsplit(".", 1)[1] for _, b, _, _ in row.stages]
        if exts != want_ext:
            errors.append("%s: %s has stages %s; %s wants %s" % (
                w, row.id, "/".join(exts) or "none", row.link, "/".join(want_ext)))
        for header, body, blob, sw in row.stages:
            st = tsv.stage_file(str(body))
            try:
                axes = tsv.stage_defines(header, st, consts)
            except tsv.Unresolved as e:
                errors.append("%s: %s: %s" % (sw, row.id, e))
                continue
            key = (st, frozenset(axes.items()))
            have = offline.get(key)
            shown = " ".join("%s=%s" % kv for kv in sorted(axes.items())) or "no defines"
            if have is None:
                errors.append("%s: %s builds %s with %s, which no offline blob is (see "
                              "test_shader_variants.py)" % (sw, row.id, st, shown))
            elif blob != have:
                errors.append("%s: %s names blob %r for %s with %s; EmbedShaders writes that as %r"
                              % (sw, row.id, blob, st, shown, have))
            blobs_used.add(blob)
    for e in enum:
        if e not in by_id:
            errors.append("%s: %s has no %s row (desktop view)" % (MODULE, e, tsv.TABLE_NAME))
    return rows, blobs_used


def check_reflection(root, offline, blobs_used, errors):
    p = root / REFL_FILE
    if not p.exists():
        errors.append("%s is missing; generate it with tools/gen_program_reflection.py" % REFL_FILE)
        return 0
    rows = re.findall(r'\{\s*"([^"]+)"\s*,\s*(RPROG_REFL_\w+)\s*,([^{}]*)\{([^{}]*)\}\s*\}', p.read_text())
    have = {}
    for blob, stage, counts, threads in rows:
        if blob in have:
            errors.append("%s: %s has two rows" % (REFL_FILE, blob))
        have[blob] = stage
        ext = blob.rsplit(".", 1)[-1]
        if REFL_STAGE.get(ext) != stage:
            errors.append("%s: %s is %s; a .%s blob is %s" % (REFL_FILE, blob, stage, ext,
                                                               REFL_STAGE.get(ext)))
        if len([c for c in counts.split(",") if c.strip()]) != 6 or \
                len([t for t in threads.split(",") if t.strip()]) != 3:
            errors.append("%s: %s: want six counts and a three-number threadcount" % (REFL_FILE, blob))
    want = set(offline.values())
    for b in sorted(want - set(have)):
        errors.append("%s: no row for offline copy %s; regenerate it" % (REFL_FILE, b))
    for b in sorted(set(have) - want):
        errors.append("%s: %s is no offline copy EmbedShaders writes; regenerate it" % (REFL_FILE, b))
    for b in sorted(blobs_used - set(have)):
        errors.append("a program names blob %s, which %s has no reflection row for" % (b, REFL_FILE))
    return len(have)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    ap.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    args = ap.parse_args(argv)
    root = args.root.resolve()
    errors = []

    texts = {}
    for path in sorted(p for p in (root / "engine").rglob("*") if p.suffix in SUFFIXES):
        rel = path.relative_to(root).as_posix()
        texts[rel] = ttr.blank(path.read_text(errors="replace"))
    # Keep going without them, so a tree from before the table still shows
    # every raw call it makes.
    for need in (MODULE, ENUM_FILE):
        if need not in texts:
            errors.append("%s is missing" % need)
            texts[need] = ""

    funcs_module = functions(texts[MODULE])
    for rel, text in texts.items():
        if rel in EXEMPT:
            continue
        scan_raw(rel, text, funcs_module if rel == MODULE else [], errors)
    check_module_shape(texts[MODULE], funcs_module, errors)
    # An #include names its file in a string, which blank() removed: read raw.
    for path in sorted(p for p in (root / "engine").rglob("*") if p.suffix in SUFFIXES):
        rel = path.relative_to(root).as_posix()
        inc = re.search(r'^\s*#\s*include\s*"gl_progid_refl\.h"', path.read_text(errors="replace"), re.M)
        if rel != MODULE and inc:
            errors.append("%s includes gl_progid_refl.h; only %s does (it defines a static table)"
                          % (rel, MODULE))
        elif rel == MODULE and not inc:
            errors.append("%s does not include gl_progid_refl.h, so R_Program_Reflection has no "
                          "rows" % MODULE)

    enum = read_enum(texts[ENUM_FILE], errors)

    shader_dir = root / "engine/shaders"
    variants, consts = tsv.read_manifest(shader_dir / "variants.txt", errors)
    _bodies, offline, _vfiles = tsv.offline_copies(shader_dir, variants, consts, errors)
    try:
        an = tsv.Analysis(root)
        rows, blobs_used = check_table(an, enum, offline, consts, errors)
    except (tsv.Fail, tsv.Unresolved) as e:
        errors.append(str(e))
        rows, blobs_used = [], set()
    nrefl = check_reflection(root, offline, blobs_used, errors)

    res = Resolver({rel: t for rel, t in texts.items() if rel not in EXEMPT}, enum, errors)
    res.run()
    check_link_modes(rows, res.reached, texts, errors)
    check_lookups(root, errors)
    for e in enum:
        if e not in res.reached:
            errors.append("%s: %s reaches no R_Program_Create call; a stale id keeps its blobs, "
                          "variants and reflection rows alive -- delete it, its row and its "
                          "variants" % (ENUM_FILE, e))

    if errors:
        for e in errors:
            print("FAIL: " + e, file=sys.stderr)
        print("%d program-routing problem(s)" % len(errors), file=sys.stderr)
        return 1
    nstages = sum(len(r.stages) for r in rows)
    print("PASS program routing: %d ids, one row each (%d stage builds, %d distinct blobs), %d "
          "reflection rows, %d R_Program_Create call sites, no program built outside "
          "gl_shader.c (#340 P1b)" % (len(enum), nstages, len(blobs_used), nrefl, res.sites))
    return 0


if __name__ == "__main__":
    sys.exit(main())
